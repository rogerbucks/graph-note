// The records of the tests-first replay (spec §12, tests_first), kept so that two branches never write the same file
// unless they replay the same commit or excuse the same test: any merge, GitHub's own among them, then joins them with
// nothing to resolve, and with no merge driver, which GitHub's merge would not read.
//
// test/tests-first/ holds one file for each replayed commit that changed a test, named after the commit, over
// baseline.json: the single record as it stood when it was split (11 Oct 2026), frozen at its head. test/seen-failing/
// holds one file for each test excused for passing before its code, named after its test file and a digest of the test.
// No field is rewritten by every update, as the single record's head was. Read against the history, the records give
// what they prove (summary) and which commits they still lack (unrecorded). Replaying a commit is scripts/tests-first.mjs.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { isDeepStrictEqual } from 'node:util';
import { JS_TEST, PY_TEST } from './tests-first-run.mjs';

const git = (repo, ...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8', maxBuffer: 1 << 28 }).trim();

/** The folder of replay records, from the repository's root: a file for each commit, and the baseline. */
export const RECORDS = 'test/tests-first';
/** The folder of reasons a test passed before its code, from the repository's root: a file for each test. */
export const EXCUSALS = 'test/seen-failing';
/** The frozen record of every commit up to its head, in the records folder. */
export const BASELINE = 'baseline.json';

// the single files the records were kept in until 11 Oct 2026, which migrate() moves over
const OLD_RECORD = 'test/tests-first.json';
const OLD_EXCUSALS = 'test/seen-failing.json';
const COMMIT_RECORD = /^([0-9a-f]{40})\.json$/;
const NOTE = 'Generated by scripts/tests-first.mjs --update: do not edit. The replay of one commit.';
const BASELINE_NOTE =
  'The tests-first record as it stood when it was split into a file for each commit (11 Oct 2026), frozen at its head: do not edit. Each commit since is recorded in a file of its own beside it.';

// names that would reach every object, were a reason looked up by them as a property (review of #69)
const REFUSED_NAMES = new Set(['__proto__', 'constructor', 'prototype']);
// what a reason holds beside its file and test
const REASON_FIELDS = new Set(['seen_failing_first', 'evidence', 'fault', 'commits']);
const isCommit = (c) => typeof c === 'string' && /^[0-9a-f]{40}$/.test(c);

/** The records or reasons kept cannot be read as they are; the message names the file and why. */
export class RecordsError extends Error {}

const json = (value) => JSON.stringify(value, null, 2) + '\n';
/** A file's JSON; one that is not JSON fails, naming the file as `shown`. */
function readJSON(file, shown) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (e) {
    throw new RecordsError(`${shown}: not JSON: ${e instanceof Error ? e.message : String(e)}`);
  }
}

/** The name of the file that keeps the reason `test`, in the test file `file`, passed before its code. */
export function excusalName(file, test) {
  const stem = basename(file).replace(/(\.test)?\.(js|mjs|py)$/, '');
  return `${stem}-${createHash('sha256').update(`${file}\n${test}`).digest('hex').slice(0, 12)}.json`;
}

/** Whether `exceptions` keeps a reason of its own for `test` in `file`: never one inherited, as `toString` is. */
export const excused = (exceptions, file, test) =>
  Object.hasOwn(exceptions, file) && Object.hasOwn(exceptions[file], test);

/** Why a reason for `test` in `file`, holding `reason`, cannot be kept, or null when it can. */
function refusal(file, test, reason) {
  if (typeof file !== 'string' || typeof test !== 'string') return 'names no test file and test';
  const refused = [file, test].find((n) => REFUSED_NAMES.has(n));
  if (refused) return `names "${refused}", which no test file or test may be called`;
  const extra = Object.keys(reason).filter((k) => !REASON_FIELDS.has(k));
  if (extra.length)
    return `holds ${extra.join(', ')}; a reason holds only file, test, seen_failing_first and evidence, and for a fault, fault and commits`;
  if ('fault' in reason && reason.fault !== true) return 'fault must be true when given';
  const c = reason.commits;
  const named = Array.isArray(c) && c.length > 0 && new Set(c).size === c.length && c.every(isCommit);
  if (reason.fault === true && !named) return 'a fault reason names, once each, the commits at which the test failed';
  if (reason.fault !== true && 'commits' in reason) return 'commits belong to a fault reason only';
  return null;
}

/** Keeps a reason in its own file, never over one kept unless `force`; gives the file's path from the root. */
export function keep(repo, file, test, reason, force) {
  const rel = `${EXCUSALS}/${excusalName(file, test)}`;
  const why = refusal(file, test, reason);
  if (why) throw new RecordsError(`${rel}: ${why}`);
  if (!force && existsSync(join(repo, rel)))
    throw new RecordsError(`${rel}: a reason for "${test}" in ${file} is kept already; --force replaces it`);
  mkdirSync(join(repo, EXCUSALS), { recursive: true });
  writeFileSync(join(repo, rel), json({ file, test, ...reason }));
  return rel;
}

/**
 * Keeps the reason `test`, in the test file `file`, passed before its code; gives the file's path from the root. A
 * reason kept already for that test is replaced only when `force` is given.
 */
export function excuse(repo, file, test, evidence, force = false) {
  return keep(repo, file, test, { seen_failing_first: false, evidence }, force);
}

/** Whether `exceptions` keeps a reason for `test` in `file` that is not for a fault: one for a test that passed first. */
export const plainExcused = (exceptions, file, test) =>
  excused(exceptions, file, test) && exceptions[file][test].fault !== true;

/** Whether `exceptions` keeps a reason that `test` in `file` failed at its own commit `commit`, among those it names. */
export const faultExcused = (exceptions, file, test, commit) =>
  excused(exceptions, file, test) &&
  exceptions[file][test].fault === true &&
  exceptions[file][test].commits.includes(commit);

/**
 * Every reason kept, by test file and test: `{ [file]: { [test]: { seen_failing_first, evidence } } }` (a fault's also
 * holds `fault: true` and its `commits`), both levels objects with no prototype, so no key reaches another object. Only
 * `.json` files are read. A file that is not JSON, names no test or one called `__proto__`, `constructor` or
 * `prototype`, holds a field no reason has, a `fault` that is not true or with no commit, or is not named for the test
 * it names, fails, naming the file.
 */
export function exceptionsIn(repo) {
  const dir = join(repo, EXCUSALS);
  const out = Object.create(null);
  const names = existsSync(dir) ? readdirSync(dir).filter((n) => n.endsWith('.json')) : [];
  for (const name of names.sort()) {
    const { file, test, ...reason } = readJSON(join(dir, name), `${EXCUSALS}/${name}`);
    const why = refusal(file, test, reason);
    if (why) throw new RecordsError(`${EXCUSALS}/${name}: ${why}`);
    const want = excusalName(file, test);
    if (name !== want)
      throw new RecordsError(`${EXCUSALS}/${name}: the reason for "${test}" in ${file} is kept in ${want}`);
    (out[file] ??= Object.create(null))[test] = reason;
  }
  return out;
}

/**
 * The records kept: the baseline (`{ head, files }`, or null when there is none), and each replayed commit's record
 * (`{ commit, files }`) by its commit. Any other file in the folder, or a record named after another commit, fails.
 */
export function readRecords(repo) {
  const dir = join(repo, RECORDS);
  const out = { baseline: null, commits: new Map() };
  for (const name of existsSync(dir) ? readdirSync(dir).sort() : []) {
    const shown = `${RECORDS}/${name}`;
    if (name === BASELINE) {
      const { head, files } = readJSON(join(dir, name), shown);
      out.baseline = { head, files };
      continue;
    }
    const commit = COMMIT_RECORD.exec(name)?.[1];
    const kept = commit ? readJSON(join(dir, name), shown) : null;
    if (!kept || kept.commit !== commit) throw new RecordsError(`${shown}: not the record of a commit named after it`);
    out.commits.set(commit, { commit, files: kept.files });
  }
  return out;
}

/** Keeps a commit's replay (`{ commit, files }`) in its own file, named after the commit. */
export function writeRecord(repo, replayed) {
  mkdirSync(join(repo, RECORDS), { recursive: true });
  writeFileSync(
    join(repo, RECORDS, `${replayed.commit}.json`),
    json({ note: NOTE, commit: replayed.commit, files: replayed.files }),
  );
}

/** Removes a commit's record. */
export function removeRecord(repo, commit) {
  rmSync(join(repo, RECORDS, `${commit}.json`), { force: true });
}

/**
 * What the records prove, by test file: the baseline's entries, then each replay in `replays`, oldest first, added in.
 * Each entry: the commits replayed and those that could not be (a new test failing at its own commit among them), the
 * new tests seen failing first, those that passed first, and how many of those have a reason in `exceptions` (`excused`).
 * A fault with a reason there (--excuse --fault) is not counted as not replayed, but as `faultsExcused`. Only the
 * test files in `current` are kept, sorted.
 */
export function tally(baseline, replays, exceptions, current) {
  const files = structuredClone(baseline?.files ?? {});
  const faultsExcused = new Map();
  for (const { commit, files: replayed } of replays)
    for (const f of replayed) {
      const e = (files[f.file] ??= {
        replayed: 0,
        notReplayed: 0,
        seenFailing: 0,
        excused: 0,
        passedFirst: [],
        notReplayedCommits: [],
      });
      // a new test failing at its own commit is kept with its file as a fault, and counts as not replayed (review of #69)
      const faulted = f.faults ?? [];
      const why = faulted.map((x) => x.problem);
      const named = [...(f.tests ?? []), ...faulted.map((x) => x.test)];
      const unreplayed = (reason) => {
        e.notReplayed++;
        e.notReplayedCommits.push({ commit, reason, ...(named.length ? { tests: named } : {}) });
      };
      if (f.notReplayed) {
        unreplayed([f.notReplayed, ...why].join('; '));
        continue;
      }
      // its other new tests are judged and counted; the commit is counted once, as not replayed when a test in it was not
      // a fault with a reason kept (--excuse --fault) is excused, and the commit counts as replayed
      if (faulted.length && !faulted.every((x) => faultExcused(exceptions, f.file, x.test, commit)))
        unreplayed(why.join('; '));
      else {
        e.replayed++;
        faultsExcused.set(f.file, (faultsExcused.get(f.file) ?? 0) + faulted.length);
      }
      e.seenFailing += f.failedFirst.length;
      for (const name of f.passedFirst) e.passedFirst.push({ commit, name });
    }
  for (const [file, e] of Object.entries(files)) {
    // `excused` counts the passed-first tests with a reason only; `faultsExcused` the faults with one, kept apart
    e.excused = e.passedFirst.filter((p) => plainExcused(exceptions, file, p.name)).length;
    e.faultsExcused = faultsExcused.get(file) ?? 0;
  }
  return Object.fromEntries(
    Object.entries(files)
      .filter(([f]) => current.has(f))
      .sort(([a], [b]) => (a < b ? -1 : 1)),
  );
}

/** What a commit changed: a status and its path, or a rename's two paths, for each file. A first commit shows none. */
export const changes = (repo, commit) =>
  git(repo, 'diff-tree', '--no-commit-id', '--name-status', '-r', '-M', commit)
    .split('\n')
    .filter(Boolean)
    .map((l) => l.split('\t'));

/** The test files among `changed` that the commit added or changed: those its replay runs. */
export const testsIn = (changed) =>
  changed
    .filter(([s]) => s !== 'D')
    .map((x) => x.at(-1) ?? '')
    .filter((f) => JS_TEST.test(f) || PY_TEST.test(f));

/** The commits since the baseline (every commit, when there is none), oldest first, merges left out. */
export const history = (repo, baseline) =>
  git(repo, 'rev-list', '--reverse', '--no-merges', 'HEAD', ...(baseline ? [`^${baseline.head}`] : []))
    .split('\n')
    .filter(Boolean);

/** The test files the repository holds now. */
const testFiles = (repo) =>
  new Set(
    git(repo, 'ls-files')
      .split('\n')
      .filter((f) => JS_TEST.test(f) || PY_TEST.test(f)),
  );

/**
 * What the records prove now: `files`, by each test file the repository holds, the commits replayed and not, the tests
 * seen failing first, those that passed first and how many of those are excused; `baseline`, the baseline's head.
 */
export function summary(repo) {
  const { baseline, commits } = readRecords(repo);
  const replays = history(repo, baseline).flatMap((c) => commits.get(c) ?? []);
  return { baseline: baseline?.head ?? null, files: tally(baseline, replays, exceptionsIn(repo), testFiles(repo)) };
}

/** `value` with the keys of every object in it sorted, so what is printed of it is stable. */
const sorted = (value) =>
  Array.isArray(value)
    ? value.map(sorted)
    : value && typeof value === 'object'
      ? Object.fromEntries(
          Object.entries(value)
            .sort(([a], [b]) => (a < b ? -1 : 1))
            .map(([k, v]) => [k, sorted(v)]),
        )
      : value;

/**
 * What the records prove, for a reader outside the repository (--tally): `summary`, with the tests that passed first
 * counted, and `excused`, each reason kept by test file and test, with its file's path from the root and its content as
 * kept. Read with the readers above, so a reason file that is malformed or names `__proto__` fails, naming it. Every
 * object has its keys sorted. Gives the JSON text, and writes nothing.
 */
export function tallyReport(repo) {
  const { baseline, files } = summary(repo);
  const counted = Object.fromEntries(
    Object.entries(files).map(([file, e]) => [file, { ...e, passedFirst: e.passedFirst.length }]),
  );
  const excused = Object.fromEntries(
    Object.entries(exceptionsIn(repo)).map(([file, tests]) => [
      file,
      Object.fromEntries(
        Object.entries(tests).map(([test, reason]) => [
          test,
          { reasonFile: `${EXCUSALS}/${excusalName(file, test)}`, reason: { file, test, ...reason } },
        ]),
      ),
    ]),
  );
  return json(sorted({ baseline, files: counted, excused }));
}

/**
 * The commits since the baseline that changed a test and have no record: each is recorded by --update on the branch
 * that made it, so no other branch replays it again, perhaps differently (review of #69).
 */
export function unrecorded(repo) {
  const { baseline, commits } = readRecords(repo);
  return history(repo, baseline).filter((c) => !commits.has(c) && testsIn(changes(repo, c)).length > 0);
}

/** Each reason in the old single file, if there is one, with the reason already kept for its test, if there is one. */
function oldReasons(repo) {
  const oldExcusals = join(repo, OLD_EXCUSALS);
  if (!existsSync(oldExcusals)) return null;
  return Object.entries(readJSON(oldExcusals, OLD_EXCUSALS)).flatMap(([file, names]) =>
    Object.entries(names).map(([test, reason]) => {
      const rel = `${EXCUSALS}/${excusalName(file, test)}`;
      const there = existsSync(join(repo, rel)) ? readJSON(join(repo, rel), rel) : null;
      return { file, test, reason, rel, there };
    }),
  );
}

/**
 * Moves records kept in the old single files over, and removes the old files: every reason into a file of its own, and
 * the old record whole into the baseline when there is none yet. When there is one, a branch's own old record is
 * dropped, never written over it: `--update` replays the commits it held since the baseline. Everything is read and
 * checked before anything is written, so a reason that would be refused leaves both folders and both old files as they
 * were (review of #69). A reason kept already, differently, is left as it is and named, for a person to choose: main
 * may have changed it since the branch began. Gives a line for each thing done or left.
 */
export function migrate(repo) {
  const reasons = oldReasons(repo);
  const refused = (reasons ?? []).flatMap((r) => {
    const why = refusal(r.file, r.test, r.reason);
    return why ? [`${r.rel}: ${why}`] : [];
  });
  if (refused.length)
    throw new RecordsError(`${OLD_EXCUSALS}: nothing is moved, as a reason cannot be kept:\n  ${refused.join('\n  ')}`);
  const oldRecord = join(repo, OLD_RECORD);
  const baseline = join(repo, RECORDS, BASELINE);
  const record = existsSync(oldRecord) && !existsSync(baseline) ? readJSON(oldRecord, OLD_RECORD) : null;
  const said = [];
  if (reasons) {
    const left = [];
    for (const { file, test, reason, rel, there } of reasons) {
      if (!there) keep(repo, file, test, reason, false);
      else if (!isDeepStrictEqual(there, { file, test, ...reason }))
        left.push(
          `${rel}: kept as it is; the branch's own reason for "${test}" in ${file} differs, so choose one. ` +
            `The branch's own evidence: ${JSON.stringify(reason.evidence)}`,
        );
    }
    rmSync(join(repo, OLD_EXCUSALS));
    const moved = reasons.filter((r) => !r.there).length;
    said.push(`${OLD_EXCUSALS}: ${moved} reason(s) moved, each into a file of its own in ${EXCUSALS}/`, ...left);
  }
  if (existsSync(oldRecord)) {
    if (record) {
      mkdirSync(join(repo, RECORDS), { recursive: true });
      writeFileSync(baseline, json({ note: BASELINE_NOTE, head: record.head, files: record.files }));
      said.push(`${OLD_RECORD}: moved whole into ${RECORDS}/${BASELINE}, frozen at ${record.head.slice(0, 7)}`);
    } else {
      said.push(
        `${OLD_RECORD}: dropped, as ${RECORDS}/${BASELINE} is there; run --update to replay the commits since it`,
      );
    }
    rmSync(oldRecord);
  }
  return said;
}
