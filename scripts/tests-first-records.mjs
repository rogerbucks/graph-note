// The records of the tests-first replay (spec §12, tests_first), kept so that two branches never write the same file
// unless they replay the same commit or excuse the same test: any merge, GitHub's own among them, then joins them with
// nothing to resolve, and with no merge driver, which GitHub's merge would not read.
//
// test/tests-first/ holds one file for each replayed commit that changed a test, named after the commit, over
// baseline.json: the single record as it stood when it was split (11 Oct 2026), frozen at its head. test/seen-failing/
// holds one file for each test excused for passing before its code, named after its test file and a digest of the test.
// No field is rewritten by every update, as the single record's head was. Replaying a commit is scripts/tests-first.mjs.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

/** The folder of replay records, from the repository's root: a file for each commit, and the baseline. */
export const RECORDS = 'test/tests-first';
/** The folder of reasons a test passed before its code, from the repository's root: a file for each test. */
export const EXCUSALS = 'test/seen-failing';
/** The frozen record of every commit up to its head, in the records folder. */
export const BASELINE = 'baseline.json';

// the single files the records were kept in until 11 Oct 2026, which migrate() moves over
const OLD_RECORD = 'test/tests-first.json';
const OLD_EXCUSALS = 'test/seen-failing.json';
const COMMIT_RECORD = /^([0-9a-f]{40})\.json$/;
const NOTE = 'Generated by scripts/tests-first.mjs --update: do not edit. The replay of one commit.';
const BASELINE_NOTE =
  'The tests-first record as it stood when it was split into a file for each commit (11 Oct 2026), frozen at its head: do not edit. Each commit since is recorded in a file of its own beside it.';

const json = (value) => JSON.stringify(value, null, 2) + '\n';
const readJSON = (file) => JSON.parse(readFileSync(file, 'utf8'));

/** The name of the file that keeps the reason `test`, in the test file `file`, passed before its code. */
export function excusalName(file, test) {
  const stem = basename(file).replace(/(\.test)?\.(js|mjs|py)$/, '');
  return `${stem}-${createHash('sha256').update(`${file}\n${test}`).digest('hex').slice(0, 12)}.json`;
}

/** Keeps a reason in its own file; gives the file's path from the repository's root. */
function keep(repo, file, test, reason) {
  const rel = `${EXCUSALS}/${excusalName(file, test)}`;
  mkdirSync(join(repo, EXCUSALS), { recursive: true });
  writeFileSync(join(repo, rel), json({ file, test, ...reason }));
  return rel;
}

/** Keeps the reason `test`, in the test file `file`, passed before its code; gives the file's path from the root. */
export function excuse(repo, file, test, evidence) {
  return keep(repo, file, test, { seen_failing_first: false, evidence });
}

/**
 * Every reason kept, by test file and test: `{ [file]: { [test]: { seen_failing_first, evidence } } }`. A file that
 * names no test, or is not named for the test it names, fails, naming the file and the name it should have.
 */
export function exceptionsIn(repo) {
  const dir = join(repo, EXCUSALS);
  const out = {};
  for (const name of existsSync(dir) ? readdirSync(dir).sort() : []) {
    const { file, test, ...reason } = readJSON(join(dir, name));
    if (typeof file !== 'string' || typeof test !== 'string')
      throw new Error(`${EXCUSALS}/${name}: names no test file and test`);
    const want = excusalName(file, test);
    if (name !== want) throw new Error(`${EXCUSALS}/${name}: the reason for "${test}" in ${file} is kept in ${want}`);
    (out[file] ??= {})[test] = reason;
  }
  return out;
}

/**
 * The records kept: the baseline (`{ head, files }`, or null when there is none), and each replayed commit's record
 * (`{ commit, files }`) by its commit. Any other file in the folder, or a record named after another commit, fails.
 */
export function readRecords(repo) {
  const dir = join(repo, RECORDS);
  const out = { baseline: null, commits: new Map() };
  for (const name of existsSync(dir) ? readdirSync(dir).sort() : []) {
    if (name === BASELINE) {
      const { head, files } = readJSON(join(dir, name));
      out.baseline = { head, files };
      continue;
    }
    const commit = COMMIT_RECORD.exec(name)?.[1];
    const kept = commit ? readJSON(join(dir, name)) : null;
    if (!kept || kept.commit !== commit)
      throw new Error(`${RECORDS}/${name}: not the record of a commit named after it`);
    out.commits.set(commit, { commit, files: kept.files });
  }
  return out;
}

/** Keeps a commit's replay (`{ commit, files }`) in its own file, named after the commit. */
export function writeRecord(repo, replayed) {
  mkdirSync(join(repo, RECORDS), { recursive: true });
  writeFileSync(
    join(repo, RECORDS, `${replayed.commit}.json`),
    json({ note: NOTE, commit: replayed.commit, files: replayed.files }),
  );
}

/** Removes a commit's record. */
export function removeRecord(repo, commit) {
  rmSync(join(repo, RECORDS, `${commit}.json`), { force: true });
}

/**
 * What the records prove, by test file: the baseline's entries, then each replay in `replays`, oldest first, added in.
 * Each entry: the commits replayed and those that could not be, the new tests seen failing first, those that passed
 * first, and how many of those have a reason in `exceptions`. Only the test files in `current` are kept, sorted.
 */
export function tally(baseline, replays, exceptions, current) {
  const files = structuredClone(baseline?.files ?? {});
  for (const { commit, files: replayed } of replays)
    for (const f of replayed) {
      const e = (files[f.file] ??= {
        replayed: 0,
        notReplayed: 0,
        seenFailing: 0,
        excused: 0,
        passedFirst: [],
        notReplayedCommits: [],
      });
      if (f.notReplayed) {
        e.notReplayed++;
        e.notReplayedCommits.push({ commit, reason: f.notReplayed, ...(f.tests?.length ? { tests: f.tests } : {}) });
        continue;
      }
      e.replayed++;
      e.seenFailing += f.failedFirst.length;
      for (const name of f.passedFirst) e.passedFirst.push({ commit, name });
    }
  for (const [file, e] of Object.entries(files))
    e.excused = e.passedFirst.filter((p) => exceptions[file]?.[p.name]).length;
  return Object.fromEntries(
    Object.entries(files)
      .filter(([f]) => current.has(f))
      .sort(([a], [b]) => (a < b ? -1 : 1)),
  );
}

/**
 * Moves records kept in the old single files over, and removes the old files: every reason into a file of its own, and
 * the old record whole into the baseline when there is none yet. When there is one, a branch's own old record is
 * dropped, never written over it: `--update` replays the commits it held since the baseline. Gives a line for each.
 */
export function migrate(repo) {
  const said = [];
  const oldExcusals = join(repo, OLD_EXCUSALS);
  if (existsSync(oldExcusals)) {
    let moved = 0;
    for (const [file, names] of Object.entries(readJSON(oldExcusals)))
      for (const [test, reason] of Object.entries(names)) {
        keep(repo, file, test, reason);
        moved++;
      }
    rmSync(oldExcusals);
    said.push(`${OLD_EXCUSALS}: ${moved} reason(s) moved, each into a file of its own in ${EXCUSALS}/`);
  }
  const oldRecord = join(repo, OLD_RECORD);
  if (existsSync(oldRecord)) {
    const baseline = join(repo, RECORDS, BASELINE);
    if (existsSync(baseline)) {
      said.push(
        `${OLD_RECORD}: dropped, as ${RECORDS}/${BASELINE} is there; run --update to replay the commits since it`,
      );
    } else {
      const { head, files } = readJSON(oldRecord);
      mkdirSync(join(repo, RECORDS), { recursive: true });
      writeFileSync(baseline, json({ note: BASELINE_NOTE, head, files }));
      said.push(`${OLD_RECORD}: moved whole into ${RECORDS}/${BASELINE}, frozen at ${head.slice(0, 7)}`);
    }
    rmSync(oldRecord);
  }
  return said;
}
