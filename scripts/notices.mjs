#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from licences/bundled.json and the licence
// texts beside it. The notices are a derivative: edit the record, never them.
//
// Usage:
//   node scripts/notices.mjs           writes THIRD_PARTY_NOTICES.md
//   node scripts/notices.mjs --check   exits 1 if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The notices text, from the record and a reader of licence text files. */
export function renderNotices(record, readText) {
  const out = [
    '<!-- Generated by scripts/notices.mjs from licences/bundled.json. Do not edit by hand. -->',
    '',
    '# Third-party notices',
    '',
    'Thoughtknot is released under the Mozilla Public License 2.0 (see LICENSE). It bundles the libraries below. Each is listed with what is compiled inside it, its licence, and where its source can be obtained.',
    '',
  ];
  for (const [key, pkg] of Object.entries(record.packages)) {
    out.push(`## ${key}`, '', `- Licence: ${pkg.licence}`, `- Source: ${pkg.source}`);
    if (pkg.inside.length) {
      out.push('- Compiled inside it:');
      for (const c of pkg.inside) out.push(`  - ${c.name} ${c.version} — ${c.licence}`);
    }
    out.push('', '```text', readText(pkg.licenceText).trimEnd(), '```', '');
    for (const c of pkg.inside) {
      out.push(`### ${c.name} ${c.version}`, '', `- Licence: ${c.licence}`, `- Source: ${c.source}`);
      if (c.note) out.push(`- ${c.note}`);
      out.push('', '```text', readText(c.licenceText).trimEnd(), '```', '');
    }
  }
  return out.join('\n');
}

function main(argv) {
  const record = JSON.parse(readFileSync(join(ROOT, 'licences/bundled.json'), 'utf8'));
  const text = renderNotices(record, (f) => readFileSync(join(ROOT, 'licences', f), 'utf8'));
  const target = join(ROOT, 'THIRD_PARTY_NOTICES.md');
  if (argv.includes('--check')) {
    const current = readFileSync(target, 'utf8');
    if (current !== text) {
      console.error('THIRD_PARTY_NOTICES.md is out of date: run node scripts/notices.mjs');
      return 1;
    }
    return 0;
  }
  writeFileSync(target, text);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
