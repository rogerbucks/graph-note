"""W3C PROV is normative for provenance (graph spec §11, §12, §24): a derivation links to its rule
with HAD_PLAN (req:11.had-plan), who proposed, decided or wrote a thing is WAS_ATTRIBUTED_TO an
agent (req:24.prov-attributed), and a revision is generated after what it supersedes
(req:12.prov-revision). Each rule is given only where the graph holds what it is about, so a graph
without provenance gains no check. The twin of provenance.js."""

from __future__ import annotations

import datetime as dt
from collections.abc import Collection
from typing import TYPE_CHECKING, Any

from graphspec.rules.judgements import resolve

if TYPE_CHECKING:
    from graphspec.rules.plain_graph import Graph, World

# the agent types: a Model counts as a SoftwareAgent wherever one is accepted (decided 16 Oct 2026)
AGENT_LABELS = frozenset({"Person", "Organization", "SoftwareAgent", "Model"})

HAD_PLAN_LABEL = "§11 req:11.had-plan: every HAD_PLAN link goes to a Rule, or to a Ref to one"
ATTRIBUTED_LABEL = (
    "§24 req:24.prov-attributed: every WAS_ATTRIBUTED_TO link goes to a Person, Organization or "
    "SoftwareAgent (a Model counts as one)"
)
REVISION_LABEL = "§12 req:12.prov-revision: every successor was generated after what it supersedes"


def is_agent(labels: Collection[str]) -> bool:
    """Whether labels type an agent: a Person, an Organization, a SoftwareAgent, or a Model, which
    counts as one."""
    return bool(AGENT_LABELS & set(labels))


def had_plan(g: Graph, a: str) -> bool:
    """Whether an activity HAD_PLAN a rule: it carries out one, so what it generated is a cache
    (§24)."""
    return bool(g.out(a, "HAD_PLAN"))


def labels_of(w: World, g: Graph, thing: str) -> set[str]:
    """The labels of what a link goes to: the thing itself, or what a Ref resolves to."""
    if not g.has(thing, "Ref"):
        return set(g.nodes[thing][0])
    p = g.p(thing)  # a Ref that names no graph resolves to nothing
    return resolve(w, {"ref": p.get("ref"), "graph": p.get("graph")})[1]


def unknown_activity(w: World, g: Graph, a: str) -> bool:
    """Whether an activity is unknown: it has no HAD_PLAN and no ASSOCIATED_WITH agent. What an
    unknown activity generated is read as a cache, so it fails closed (§24); an activity a Person
    or a Model is associated with, without a plan, is ordinary work."""
    return not had_plan(g, a) and not any(
        is_agent(labels_of(w, g, e[2])) for e in g.out(a, "ASSOCIATED_WITH")
    )


def activity_warnings(w: World, name: str) -> list[str]:
    """The warnings for work generated by an unknown activity, sorted: each names the activity and
    the fix."""
    g = w[name]
    made: dict[str, list[str]] = {}
    for e in g.edges:
        if e[1] == "WAS_GENERATED_BY" and g.has(e[2], "Activity") and unknown_activity(w, g, e[2]):
            made.setdefault(e[2], []).append(e[0])
    return sorted(
        f"{a} has no HAD_PLAN and no ASSOCIATED_WITH agent, so what it generated "
        f"({', '.join(sorted(xs))}) is read as a cache: add ({a})-[:HAD_PLAN]->(its Rule), or "
        f"associate {a} with its agent"
        for a, xs in made.items()
    )


def when(v: Any) -> dt.datetime | None:
    """The instant a value says: a date is its midnight; anything else says none."""
    if isinstance(v, dt.datetime):
        return v
    if isinstance(v, dt.date):
        return dt.datetime(v.year, v.month, v.day)
    return None


def prov_rules(w: World, name: str) -> list[tuple[str, bool, str]]:
    """The provenance rules that apply to graph `name` of world `w`, as [(label, ok, detail)]."""
    g = w[name]
    out = []
    # HAD_PLAN is the only marker of a derivation; its target is the rule's own node (a Rule, whose
    # id names the engine function and version, §6), or a Ref that resolves to one
    plans = [e for e in g.edges if e[1] == "HAD_PLAN"]
    if plans:
        bad = [(e[0], e[2]) for e in plans if "Rule" not in labels_of(w, g, e[2])]
        out.append((HAD_PLAN_LABEL, not bad, f"{bad[:4]} — a plan is a Rule, or a Ref to one"))
    attributed = [e for e in g.edges if e[1] == "WAS_ATTRIBUTED_TO"]
    if attributed:
        bad = [(e[0], e[2]) for e in attributed if not is_agent(labels_of(w, g, e[2]))]
        out.append(
            (
                ATTRIBUTED_LABEL,
                not bad,
                f"{bad[:4]} — attribute to a Person, Organization or SoftwareAgent",
            )
        )
    pairs = [
        (e[0], e[2], when(g.p(e[0]).get("generated_at")), when(g.p(e[2]).get("generated_at")))
        for e in g.edges
        if e[1] == "SUPERSEDES"
    ]
    pairs = [x for x in pairs if x[2] is not None and x[3] is not None]
    if pairs:
        bad = [(s, p) for s, p, ts, tp in pairs if ts < tp]
        out.append(
            (
                REVISION_LABEL,
                not bad,
                f"{bad[:4]} — a successor is generated after what it supersedes",
            )
        )
    return out
