// W3C PROV is normative for provenance (graph spec §11, §12, §24): a derivation links to its rule with HAD_PLAN, and
// only to a Rule (req:11.had-plan), who proposed, decided or wrote a thing is WAS_ATTRIBUTED_TO an agent (req:24.prov-attributed), and
// a revision is generated after what it supersedes (req:12.prov-revision). Each rule is given only where the graph holds
// what it is about, so a graph without provenance gains no check. The twin of provenance.py.
'use strict';

const { isTime } = require('../values/times.js');
const { resolve } = require('./judgements.js');

// the agent types: a Model counts as a SoftwareAgent wherever one is accepted (decided 16 Oct 2026)
const AGENT_LABELS = ['Person', 'Organization', 'SoftwareAgent', 'Model'];
/** Whether labels type an agent: a Person, an Organization, a SoftwareAgent, or a Model, which counts as one. */
const isAgent = (labels) => AGENT_LABELS.some((x) => labels.has(x));
/** Whether an activity HAD_PLAN a rule: it carries out one, so what it generated is a cache (§24). */
const hadPlan = (g, a) => g.out(a, 'HAD_PLAN').length > 0;
// the labels of what a link goes to: the thing itself, or what a Ref resolves to
const labelsOf = (w, g, id) => (g.has(id, 'Ref') ? resolve(w, g.p(id))[1] : g.nodes.get(id)[0]);
/**
 * Whether an activity is unknown: it has no HAD_PLAN and no ASSOCIATED_WITH agent. What an unknown activity generated is
 * read as a cache, so it fails closed (§24); an activity a Person or a Model is associated with, without a plan, is
 * ordinary work.
 */
const unknownActivity = (w, g, a) =>
  !hadPlan(g, a) && !g.out(a, 'ASSOCIATED_WITH').some((e) => isAgent(labelsOf(w, g, e[2])));

/** The warnings for work generated by an unknown activity, sorted: each names the activity and the fix. */
function activityWarnings(w, name) {
  const g = w[name],
    made = new Map();
  for (const e of g.edges)
    if (e[1] === 'WAS_GENERATED_BY' && g.has(e[2], 'Activity') && unknownActivity(w, g, e[2]))
      (made.get(e[2]) ?? made.set(e[2], []).get(e[2])).push(e[0]);
  return [...made]
    .map(
      ([a, xs]) =>
        `${a} has no HAD_PLAN and no ASSOCIATED_WITH agent, so what it generated (${xs.sort().join(', ')}) is read as a cache: add (${a})-[:HAD_PLAN]->(its Rule), or associate ${a} with its agent`,
    )
    .sort();
}
// the instant a value says, to compare as text: a date is its midnight
const when = (v) => (isTime(v) ? (v.kind === 'date' ? v.s + 'T00:00:00' : v.s) : null);

/** The provenance rules that apply to graph `name` of world `w`, as [label, ok]. */
function provRules(w, name) {
  const g = w[name],
    out = [];
  // HAD_PLAN is the only marker of a derivation; its target is the rule's own node (a Rule, whose id names the engine
  // function and version, §6), or a Ref that resolves to one
  const plans = g.edges.filter((e) => e[1] === 'HAD_PLAN');
  if (plans.length)
    out.push([
      '§11 req:11.had-plan: every HAD_PLAN link goes to a Rule, or to a Ref to one',
      plans.every((e) => labelsOf(w, g, e[2]).has('Rule')),
    ]);
  const attributed = g.edges.filter((e) => e[1] === 'WAS_ATTRIBUTED_TO');
  if (attributed.length)
    out.push([
      '§24 req:24.prov-attributed: every WAS_ATTRIBUTED_TO link goes to a Person, Organization or SoftwareAgent (a Model counts as one)',
      attributed.every((e) => isAgent(labelsOf(w, g, e[2]))),
    ]);
  const revisions = g.edges
    .filter((e) => e[1] === 'SUPERSEDES')
    .map((e) => [when(g.p(e[0]).generated_at), when(g.p(e[2]).generated_at)])
    .filter(([successor, predecessor]) => successor !== null && predecessor !== null);
  if (revisions.length)
    out.push([
      '§12 req:12.prov-revision: every successor was generated after what it supersedes',
      revisions.every(([successor, predecessor]) => successor >= predecessor),
    ]);
  return out;
}

module.exports = { AGENT_LABELS, isAgent, hadPlan, activityWarnings, provRules };
